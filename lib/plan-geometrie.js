/**
 * Геометрия плана залов — чистые функции, без базы и без React.
 *
 * Живёт отдельным модулем, потому что нужна с обеих сторон: серверный расчёт
 * соседей (`lib/stands.js`) и два клиентских компонента, которые рисуют план.
 * Импортировать `lib/stands.js` в браузерный компонент нельзя — он тянет
 * за собой служебный ключ Supabase.
 *
 * ## Почему размеров два комплекта
 *
 * `breite_m` / `tiefe_m` / `flaeche_m2` — договорные: они из прайса, они же
 * попадают в счёт. `plan_b` / `plan_t` — как площадка нарисована на публичном
 * плане motozuerich.ch. Это схема, а не чертёж, и у части площадок одно
 * с другим расходится: весь ярус Galerie нарисован полосой одинаковой глубины
 * 2.78 м, хотя площади там от 7 до 84 м².
 *
 * Рисуем по `plan_*`, считаем и продаём по договорным. Смешать их в одну пару
 * колонок нельзя: триггер `mz_stands_flaeche` пересчитывает площадь из сторон,
 * и нарисованный прямоугольник молча переписал бы проданные метры.
 */

/**
 * Метры из базы. PostgREST отдаёт numeric строкой ('10.50'), поэтому приведение
 * нужно — но пропуск обязан остаться пропуском.
 *
 * `Number(null)` равен нулю и проходит проверку на конечность. Без этой отсечки
 * площадка без координат превращается в точку в углу зала: попадает в соседи
 * к тому, кто стоит у начала отсчёта, и рисуется поверх него. Ровно это
 * поймал тест на соседей.
 */
export function meter(raw) {
  if (raw === null || raw === undefined || raw === '') return NaN;
  return Number(raw);
}

/**
 * Прямоугольник площадки на плане, в метрах: `{x, y, w, h}`.
 *
 * `null`, если геометрии нет. Это штатное состояние, а не сбой: две площадки
 * StageOne на публичном плане отсутствуют вовсе, а новый зал может появиться
 * в каталоге раньше, чем его разметят. Такие площадки продаются списком.
 *
 * Размер берём с плана, а при его отсутствии — договорный: так зал, который
 * разметили сами, рисуется без отдельной ветки.
 */
export function planRect(stand) {
  if (!stand) return null;

  const x = meter(stand.pos_x);
  const y = meter(stand.pos_y);
  const w = meter(stand.plan_b ?? stand.breite_m);
  const h = meter(stand.plan_t ?? stand.tiefe_m);

  if (![x, y, w, h].every(Number.isFinite)) return null;
  return { x, y, w, h };
}

/**
 * Подпись внутри прямоугольника.
 *
 * Короткое обозначение с публичного плана, если оно есть: «Galerie 8A»
 * в прямоугольник 3 × 2.8 м не влезает ни при каком масштабе, «G8A» влезает.
 * В Halle D и Halle 550 обозначения совпадают с нашими, так что там подпись
 * не меняется.
 *
 * Договорный номер при этом никуда не девается — он в списке под планом
 * и в карточке справа. Пока два набора номеров не сведены, показывать оба
 * честнее, чем выбрать один и надеяться, что клиент смотрел ту же схему.
 */
export function planLabel(stand) {
  return stand?.plan_id || stand?.id || '';
}
