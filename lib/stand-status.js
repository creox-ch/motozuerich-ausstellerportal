/**
 * Статусы площадок: подписи и цвета.
 *
 * Один модуль на витрину и кабинет. До этого палитра была скопирована в два
 * компонента, и первая же правка развела бы их: на публичном плане площадка
 * зелёная, в кабинете — серая, и никто не понимает, кто прав.
 *
 * ЧТО ЗДЕСЬ ВАЖНО, КРОМЕ КРАСОТЫ.
 *
 * Цвет несёт смысл — «можно взять» или «занято», — поэтому он обязан читаться
 * с одного взгляда и не только цветом. Прежняя палитра состояла из четырёх
 * почти белых оттенков: разницу было видно, лишь положив их рядом. Теперь
 * различаются и тон, и светлота, а подпись статуса всё равно дублируется
 * текстом в списке и в `aria-label` — цвет остаётся подсказкой, а не
 * единственным носителем смысла.
 *
 * Четыре цвета различаются НЕ ТОЛЬКО ТОНОМ, но и светлотой — лесенкой:
 * занято (самый тёмный) → зарезервировано → свободно → не продаётся (самый
 * светлый). Это не эстетика: первая версия этой палитры была ярче прежней,
 * но зелёный и серо-синий совпали по светлоте, и в оттенках серого — а значит
 * и для дальтоника — они сливались. Поймал тест, а не глаз.
 *
 * Номер площадки печатается поверх заливки цветом `--ink` (#12253F). Все
 * четыре фона проверены на контраст с ним: минимум 4.9:1 при требуемых 4.5:1.
 * Поэтому фон нельзя затемнять «для яркости» — подпись станет нечитаемой.
 *
 * Своя площадка в кабинете (`EIGENE_FARBE`) по светлоте близка к «не
 * продаётся», и это осознанно: она дополнительно обведена тёмной рамкой
 * и подписана жирным, так что путать не с чем.
 */

export const STATUS_TEXT = {
  frei: 'frei',
  reserviert: 'reserviert',
  vergeben: 'vergeben',
  gesperrt: 'nicht buchbar',
};

/**
 * Порядок здесь — по «температуре доступности», от бери до не предлагается.
 * Он же задаёт порядок легенды.
 */
export const STATUS_FARBE = {
  // Зелёный — единственный статус, ради которого человек пришёл.
  frei: '#7CE0AC',
  // Оранжевый, а не жёлтый: в кабинете жёлтым помечена своя площадка,
  // и два жёлтых рядом слились бы.
  reserviert: '#EE9F35',
  // Самый тёмный: занято — это плотное, определённое состояние.
  vergeben: '#7B93B5',
  // Самый светлый намеренно: «не продаётся» должно уходить на задний план.
  gesperrt: '#E8ECF1',
};

/** Обводка площадки на плане. */
export const STAND_RAHMEN = '#8FA0B8';

/** Своя площадка в кабинете — брендовый жёлтый, ярче всего остального. */
export const EIGENE_FARBE = '#FBF142';

/** Цвет статуса с запасным значением: неизвестный статус не должен ломать план. */
export function statusFarbe(status) {
  return STATUS_FARBE[status] || '#E7EDF6';
}

/** Подпись статуса; для незнакомого показываем как есть, а не пустоту. */
export function statusText(status) {
  return STATUS_TEXT[status] || status || '';
}
