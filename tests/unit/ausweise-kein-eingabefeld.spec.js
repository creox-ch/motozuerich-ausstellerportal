import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { test, expect } from '@playwright/test';

/**
 * Unit: раздел Ausweise не собирает данные.
 *
 * Тест необычный — он читает исходник страницы, а не её поведение. Причина
 * в том, что защищаемое здесь правило юридическое, а не функциональное:
 * раздел собирает имена и функции чужих сотрудников, и до вычитки
 * Datenschutz юристом хранить их нельзя. Человек из такого списка нам ничего
 * не разрешал — его вносит работодатель, а спрашивают с нас.
 *
 * Обычный тест поведения здесь не поможет: страница закрыта сессией, а через
 * пустую сессию до неё не добраться. Зато появление в файле поля ввода видно
 * сразу — и именно оно означает, что запрет нарушен.
 *
 * Когда Datenschutz будет проверен (docs/rechtliches-review.md), этот тест
 * удаляется вместе с плашкой на странице — осознанно, одной правкой.
 */

// Путь от корня проекта: Playwright запускается оттуда, где лежит его
// конфигурация. import.meta здесь недоступен — файлы собираются как CommonJS.
const SEITE = join(process.cwd(), 'app', 'portal', 'ausweise', 'page.jsx');

const quelle = readFileSync(SEITE, 'utf8');

test('на странице нет полей ввода', () => {
  // Ищем открывающие теги, а не слова: слово «input» встречается
  // в комментариях и не значит ничего.
  expect(quelle).not.toMatch(/<input\b/i);
  expect(quelle).not.toMatch(/<textarea\b/i);
  expect(quelle).not.toMatch(/<select\b/i);
});

test('страница ничего не отправляет', () => {
  expect(quelle).not.toMatch(/<form\b/i);
  expect(quelle).not.toMatch(/\bfetch\s*\(/);
});

test('страница остаётся серверной — без клиентского состояния', () => {
  // 'use client' здесь означал бы, что кто-то собрался делать интерактив.
  expect(quelle).not.toMatch(/['"]use client['"]/);
});

test('плашка о недоступности раздела на месте', () => {
  // Плашка — единственное, что отличает честный предпросмотр от обещания.
  //
  // Эта проверка заодно страхует три предыдущие. Все они отрицательные,
  // и на пустой строке прошли бы вхолостую — например если файл переедет
  // и читать станет нечего. Одно утверждение «в файле есть вот это»
  // превращает такую поломку в красный тест, а не в тихое «всё хорошо».
  expect(quelle).toMatch(/NochNicht/);
});
